import fs from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { createServer } from 'vite';

const appRoot = fileURLToPath(new URL('..', import.meta.url));
const repoRoot = path.resolve(appRoot, '../..');
const outputPath = path.join(repoRoot, 'supabase/functions/_shared/duo_authority_room_manifest.ts');

const server = await createServer({
  root: appRoot,
  configFile: false,
  logLevel: 'silent',
  appType: 'custom',
  server: { middlewareMode: true },
});

try {
  const [{ createRoomBoundCanonicalEncounterState }, { roomPropColliders }] = await Promise.all([
    server.ssrLoadModule('/src/game/duoCanonicalEncounterFactory.ts'),
    server.ssrLoadModule('/src/game/roomCollision3D.ts'),
  ]);
  const rooms = {};
  for (let room = 1; room <= 100; room += 1) {
    const state = createRoomBoundCanonicalEncounterState({
      runId: 'manifest',
      runAttempt: 1,
      chapter: 1,
      room,
      seed: 1,
      authorityStartedAtMs: 0,
      actors: [
        { actorId: 'slot-0', classKey: 'warrior' },
        { actorId: 'slot-1', classKey: 'warrior' },
      ],
    });
    rooms[room] = {
      mapWidth: 24,
      mapHeight: 32,
      walkableBounds: { minX: 80, minY: 80, maxX: 880, maxY: 1200 },
      actorSpawns: state.actors.map(({ x, y }) => ({ x, y })),
      enemies: state.enemies.map(({ enemyType, x, y }) => ({ enemyType, x, y })),
      colliders: roomPropColliders(room).map(({ x, z, halfW, halfH }) => ({ x, z, halfW, halfH })),
    };
  }

  const json = JSON.stringify(rooms);
  const content = `// Generated by artifacts/dungeon-rpg/scripts/generate-duo-authority-room-manifest.mjs.\n`
    + `// This checked-in data keeps the Supabase Edge graph pure while a permanent contract\n`
    + `// compares every room against the authored browser sources.\n`
    + `export type DuoAuthorityRoomEnemyType = 'slime' | 'goblin' | 'skeleton' | 'orc' | 'spider' | 'vampire' | 'demon' | 'golem' | 'boss';\n\n`
    + `export type DuoAuthorityRoomManifestEntry = Readonly<{\n`
    + `  mapWidth: number;\n  mapHeight: number;\n`
    + `  walkableBounds: Readonly<{ minX: number; minY: number; maxX: number; maxY: number }>;\n`
    + `  actorSpawns: readonly Readonly<{ x: number; y: number }>[];\n`
    + `  enemies: readonly Readonly<{ enemyType: DuoAuthorityRoomEnemyType; x: number; y: number }>[];\n`
    + `  colliders: readonly Readonly<{ x: number; z: number; halfW: number; halfH: number }>[];\n`
    + `}>;\n\n`
    + `export const DUO_AUTHORITY_ROOM_MANIFEST: Readonly<Record<number, DuoAuthorityRoomManifestEntry>> = Object.freeze(${json});\n`;
  await fs.mkdir(path.dirname(outputPath), { recursive: true });
  await fs.writeFile(outputPath, content);
} finally {
  await server.close();
}
